def block(version=VERSION):
    if version not in {1,2}:
        raise ValueError('Unknown autonomous input policy version')
    rule = RULE_V1 if version == 1 else RULE_V1 + '\n\n' + GOAL_RULES
    return START + '\n' + rule + '\n' + END


def input_block(version=VERSION):
    # Previously admitted payloads retain their exact version-one bytes.
    if version == 1:
        return block(1)
    if version != VERSION:
        raise ValueError('Unknown autonomous input policy version')
    return START + '\n' + INPUT_RULE_V2 + '\n' + END


def owner_prompt(text):
    pattern = r'\n*' + re.escape(START) + r'\n.*?\n' + re.escape(END)
    base = re.sub(pattern, '', text, flags=re.S).rstrip()
    return (base + '\n\n' if base else '') + block()
